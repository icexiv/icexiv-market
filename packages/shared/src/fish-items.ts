/** 该物品是否为水产品（鱼）。 */
export function isFishItem(itemId: number): boolean {
  let lo = 0
  let hi = FISH_RANGES.length - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    const range = FISH_RANGES[mid]
    if (itemId < range[0]) hi = mid - 1
    else if (itemId > range[1]) lo = mid + 1
    else return true
  }
  return false
}
